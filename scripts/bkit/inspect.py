"""Inspection: what is actually in the scene, measured - not assumed.

    from bkit import inspect as I
    rep = I.scene_report()               # summary dict (JSON-safe)
    h = I.mesh_health(obj)               # topology/normal problems of the evaluated mesh
    hits = I.intersections(objs)         # penetrating object pairs (contacts separated)
    cov = I.camera_coverage(cam, objs)   # in-frame status and frame fill
    st = I.image_stats("render.png")     # exposure / clipping / fireflies
"""
import os

import bmesh
import bpy
from mathutils import Vector
from mathutils.bvhtree import BVHTree

from . import compat

GEOMETRY_TYPES = {"MESH", "CURVE", "SURFACE", "FONT", "META", "CURVES", "POINTCLOUD", "VOLUME"}


def _r(v, n=3):
    return [round(x, n) for x in v]


def _tris_of_mesh(me):
    import numpy as np
    n = len(me.polygons)
    if not n:
        return 0
    lt = np.empty(n, dtype=np.int32)
    me.polygons.foreach_get("loop_total", lt)
    return int((lt - 2).sum())


def _render_visible_collections(scene):
    """Names of collections whose whole chain is renderable in the active view layer."""
    vis = set()

    def walk(lc, ok):
        coll = lc.collection
        ok = ok and not lc.exclude and not coll.hide_render
        if ok:
            vis.add(coll.name)
        for ch in lc.children:
            walk(ch, ok)

    walk(bpy.context.view_layer.layer_collection, True)
    return vis


def is_render_visible(ob, _vis=None):
    """Object renders directly: not hide_render and in at least one render-visible collection.
    (Objects in a hidden 'Assets' collection can still appear as GN/collection instances.)"""
    if ob.hide_render:
        return False
    vis = _vis if _vis is not None else _render_visible_collections(bpy.context.scene)
    return any(c.name in vis for c in ob.users_collection)


def renderable(scene=None, include_hidden=False):
    scene = scene or bpy.context.scene
    vis = _render_visible_collections(scene)
    out = []
    for ob in scene.objects:
        if ob.type not in GEOMETRY_TYPES:
            continue
        if not include_hidden and (not is_render_visible(ob, vis) or ob.name.startswith("CUT_")):
            continue
        out.append(ob)
    return out


def evaluated_tris(scene=None):
    """Triangles that will actually render, including GN/particle/collection instances."""
    scene = scene or bpy.context.scene
    dg = bpy.context.evaluated_depsgraph_get()
    cache = {}
    per_obj = {}    # including instances generated by the object (GN scatter, particles)
    own = {}        # the object's own geometry only (memory / modelling budget)
    total = 0
    instances = 0
    for inst in dg.object_instances:
        ob = inst.object
        if ob.type not in GEOMETRY_TYPES or not inst.show_self:
            continue
        orig = (inst.parent.original if inst.is_instance and inst.parent else ob.original)
        if orig.hide_render and not inst.is_instance:
            continue
        if ob.type == "MESH":
            key = ob.data.as_pointer()
            if key not in cache:
                cache[key] = _tris_of_mesh(ob.data)
            t = cache[key]
        else:
            key = ("obj", ob.as_pointer())
            if key not in cache:
                try:
                    me = ob.to_mesh()
                    cache[key] = _tris_of_mesh(me) if me else 0
                    ob.to_mesh_clear()
                except RuntimeError:
                    cache[key] = 0
            t = cache[key]
        total += t
        if inst.is_instance:
            instances += 1
        else:
            own[orig.name] = own.get(orig.name, 0) + t
        per_obj[orig.name] = per_obj.get(orig.name, 0) + t
    return {"total": total, "instances": instances, "per_object": per_obj, "own": own}


def is_instancer(ob):
    """Object whose own mesh is empty and whose output is instances (GN scatter, etc.)."""
    return (ob.type == "MESH" and len(ob.data.polygons) == 0
            and any(m.type in ("NODES", "PARTICLE_SYSTEM") for m in ob.modifiers))


def world_summary(scene):
    w = scene.world
    if not w:
        return {"type": "none"}
    if not w.use_nodes or not w.node_tree:
        return {"type": "color", "color": _r(w.color)}
    nodes = w.node_tree.nodes
    kinds = [n.bl_idname for n in nodes]
    strength = None
    for n in nodes:
        if n.bl_idname == "ShaderNodeBackground":
            strength = n.inputs["Strength"].default_value
    t = "sky" if "ShaderNodeTexSky" in kinds else "hdri" if "ShaderNodeTexEnvironment" in kinds else (
        "gradient" if "ShaderNodeValToRGB" in kinds else "color")
    info = {"type": t, "strength": round(strength, 3) if strength is not None else None}
    if t == "color":
        for n in nodes:
            if n.bl_idname == "ShaderNodeBackground":
                info["color"] = _r(n.inputs["Color"].default_value[:3])
    return info


def image_status():
    out = []
    for img in bpy.data.images:
        if img.source in ("GENERATED", "VIEWER") or img.type in ("RENDER_RESULT", "COMPOSITING"):
            continue
        path = bpy.path.abspath(img.filepath, library=img.library) if img.filepath else ""
        out.append({"name": img.name, "path": img.filepath, "exists": bool(path) and os.path.exists(path),
                    "packed": img.packed_file is not None, "users": img.users,
                    "colorspace": img.colorspace_settings.name, "size": list(img.size)})
    return out


def collections_tree(coll=None):
    coll = coll or bpy.context.scene.collection
    return {"name": coll.name, "objects": len(coll.objects),
            "children": [collections_tree(c) for c in coll.children]}


def object_info(ob, tris=None):
    d = {"name": ob.name, "type": ob.type, "collection": [c.name for c in ob.users_collection],
         "location": _r(ob.matrix_world.translation), "dimensions": _r(ob.dimensions),
         "rotation_deg": _r([x * 57.29578 for x in ob.rotation_euler], 1), "scale": _r(ob.scale),
         "hide_render": ob.hide_render}
    if ob.parent:
        d["parent"] = ob.parent.name
    if ob.modifiers:
        d["modifiers"] = ["%s:%s" % (m.type, m.name) for m in ob.modifiers]
    if hasattr(ob.data, "materials"):
        d["materials"] = [m.name if m else None for m in ob.data.materials]
    if tris is not None:
        d["tris"] = tris
    if ob.type == "LIGHT":
        L = ob.data
        d.update(light_type=L.type, energy=round(L.energy, 3), color=_r(L.color))
    if ob.type == "CAMERA":
        c = ob.data
        d.update(lens=round(c.lens, 2), cam_type=c.type, dof=c.dof.use_dof)
    if ob.animation_data and ob.animation_data.action:
        fr = [kp.co.x for fc in compat.id_fcurves(ob) for kp in fc.keyframe_points]
        if fr:
            d["keyframes"] = [min(fr), max(fr)]
    return d


def scene_report(scene=None, objects=True, max_objects=150):
    sc = scene or bpy.context.scene
    r = sc.render
    tri = evaluated_tris(sc)
    counts = {}
    for ob in sc.objects:
        counts[ob.type] = counts.get(ob.type, 0) + 1
    rep = {
        "file": bpy.data.filepath or "(unsaved)",
        "blender": bpy.app.version_string,
        "scene": sc.name,
        "engine": r.engine,
        "resolution": [r.resolution_x, r.resolution_y, r.resolution_percentage],
        "frames": [sc.frame_start, sc.frame_end, r.fps],
        "camera": sc.camera.name if sc.camera else None,
        "color": {"view": sc.view_settings.view_transform, "look": sc.view_settings.look,
                  "exposure": sc.view_settings.exposure},
        "world": world_summary(sc),
        "counts": counts,
        "tris_total": tri["total"],
        "instances": tri["instances"],
        "collections": collections_tree(sc.collection),
        "materials": len(bpy.data.materials),
        "images": image_status(),
        "libraries": [{"path": l.filepath, "exists": os.path.exists(bpy.path.abspath(l.filepath))}
                      for l in bpy.data.libraries],
    }
    if r.engine == "CYCLES":
        c = sc.cycles
        rep["cycles"] = {"samples": c.samples, "adaptive": c.use_adaptive_sampling,
                         "denoise": c.use_denoising, "device": c.device, "bounces": c.max_bounces}
    elif r.engine.startswith("BLENDER_EEVEE"):
        rep["eevee"] = {"samples": sc.eevee.taa_render_samples,
                        "raytracing": getattr(sc.eevee, "use_raytracing", None)}
    if objects:
        obs = sorted(sc.objects, key=lambda o: (o.type, o.name))
        rep["objects"] = [object_info(o, tri["per_object"].get(o.name)) for o in obs[:max_objects]]
        if len(obs) > max_objects:
            rep["objects_truncated"] = len(obs) - max_objects
    return rep


# --------------------------------------------------------------------------- geometry health
def _eval_bmesh(ob, world=False):
    dg = bpy.context.evaluated_depsgraph_get()
    ev = ob.evaluated_get(dg)
    me = ev.to_mesh()
    bm = bmesh.new()
    bm.from_mesh(me)
    ev.to_mesh_clear()
    if world:
        bm.transform(ob.matrix_world)
    return bm


def mesh_health(ob, evaluated=True, doubles_dist=1e-5, max_verts=400000):
    """Topology and normal problems. Boundary edges are reported separately (legit on open
    surfaces such as planes/terrain); `multi_face_edges` (>2 faces) are always suspicious."""
    if ob.type != "MESH":
        return {"skipped": "not a mesh"}
    bm = _eval_bmesh(ob) if evaluated else bmesh.new()
    if not evaluated:
        bm.from_mesh(ob.data)
    try:
        if len(bm.verts) > max_verts:
            return {"skipped": "too large (%d verts)" % len(bm.verts)}
        bm.normal_update()
        boundary = sum(1 for e in bm.edges if len(e.link_faces) == 1)
        multi = sum(1 for e in bm.edges if len(e.link_faces) > 2)
        wire = sum(1 for e in bm.edges if len(e.link_faces) == 0)
        inconsistent = sum(1 for e in bm.edges if len(e.link_faces) == 2 and not e.is_contiguous)
        loose_v = sum(1 for v in bm.verts if not v.link_edges)
        zero = sum(1 for f in bm.faces if f.calc_area() < 1e-12)
        ngons = sum(1 for f in bm.faces if len(f.verts) > 4)
        dbl = len(bmesh.ops.find_doubles(bm, verts=bm.verts, dist=doubles_dist)["targetmap"])
        closed = boundary == 0 and multi == 0 and wire == 0 and len(bm.faces) > 0
        vol = bm.calc_volume(signed=True) if closed else None
        mw = ob.matrix_world
        det = mw.to_3x3().determinant()
        return {
            "verts": len(bm.verts), "faces": len(bm.faces),
            "closed": closed, "boundary_edges": boundary, "multi_face_edges": multi,
            "wire_edges": wire, "inconsistent_normal_edges": inconsistent,
            "inverted": bool(closed and vol is not None and vol < 0),
            "loose_verts": loose_v, "zero_area_faces": zero, "ngons": ngons, "duplicate_verts": dbl,
            "scale": _r(ob.scale), "negative_scale": det < 0,
            "unapplied_scale": any(abs(s - 1.0) > 1e-4 for s in ob.scale),
        }
    finally:
        bm.free()


def _straddles(face, other, eps):
    no, co = other.normal, other.verts[0].co
    d = [no.dot(v.co - co) for v in face.verts]
    return min(d) < -eps and max(d) > eps


def _face_samples(face):
    pts = [v.co.copy() for v in face.verts]
    pts += [(e.verts[0].co + e.verts[1].co) / 2 for e in face.edges]
    pts.append(face.calc_center_median())
    return pts


_RAYS = (Vector((0.577, 0.583, 0.571)), Vector((-0.31, 0.22, 0.925)), Vector((0.21, -0.91, 0.36)))


def _inside_parity(p, tree, max_hits=64):
    """Point-in-closed-mesh by ray crossing parity (majority over 3 skewed rays)."""
    votes = 0
    for d in _RAYS:
        d = d.normalized()
        o, n = p.copy(), 0
        while n < max_hits:
            hit = tree.ray_cast(o, d)
            if hit[0] is None:
                break
            n += 1
            o = hit[0] + d * 1e-6
        votes += n % 2
    return votes >= 2


def _depth_into(points, tree, closed):
    """Deepest sample point inside the other mesh = distance to its surface.
    Closed meshes: ray parity (robust). Open meshes (floors as planes, terrain): outward-normal
    sign of the nearest face (nearest-normal alone misfires at edges/corners of closed meshes)."""
    depth = 0.0
    for p in points:
        q, n, _, dist = tree.find_nearest(p)
        if q is None or dist <= depth:
            continue
        inside = _inside_parity(p, tree) if closed else (p - q).dot(n) < 0
        if inside:
            depth = dist
    return depth


def intersections(objs=None, max_tris=150000, ignore_assemblies=True, contact_eps=1e-4):
    """Pairs of objects whose surfaces intersect. Splits coplanar 'contact' (resting on a floor)
    from real 'penetration'. Objects sharing a top-level parent are one assembly (skipped) unless
    ignore_assemblies=False. Set obj["bk_allow_intersect"]=True to whitelist an object.
    """
    objs = [o for o in (objs or renderable()) if o.type == "MESH" and not o.get("bk_allow_intersect")]
    data = []
    skipped = []
    for ob in objs:
        bm = _eval_bmesh(ob, world=True)
        if len(bm.faces) * 2 > max_tris:
            skipped.append(ob.name)
            bm.free()
            continue
        bm.faces.ensure_lookup_table()
        if not bm.faces:
            bm.free()
            continue
        mn = Vector((min(v.co.x for v in bm.verts), min(v.co.y for v in bm.verts), min(v.co.z for v in bm.verts)))
        mx = Vector((max(v.co.x for v in bm.verts), max(v.co.y for v in bm.verts), max(v.co.z for v in bm.verts)))
        root = ob
        while root.parent:
            root = root.parent
        data.append((ob, bm, BVHTree.FromBMesh(bm), mn, mx, root))
    out = []
    for i in range(len(data)):
        a, bma, ta, amn, amx, ra = data[i]
        for j in range(i + 1, len(data)):
            b, bmb, tb, bmn, bmx, rb = data[j]
            if ignore_assemblies and ra == rb and ra is not None and (a.parent or b.parent):
                continue
            if any(amx[k] < bmn[k] - contact_eps or bmx[k] < amn[k] - contact_eps for k in range(3)):
                continue
            pairs = ta.overlap(tb)
            if not pairs:
                continue
            pen, sa, sb = 0, set(), set()
            for fa, fb in pairs:
                f1, f2 = bma.faces[fa], bmb.faces[fb]
                # Candidate = each face crosses the other's plane by more than eps.
                # Touching (shared plane, edge on a floor) is 'contact', not a defect.
                if _straddles(f1, f2, contact_eps) and _straddles(f2, f1, contact_eps):
                    pen += 1
                    sa.add(fa)
                    sb.add(fb)
            depth = 0.0
            if pen:  # how deep does one surface actually go inside the other?
                closed_a = all(len(e.link_faces) == 2 for e in bma.edges)
                closed_b = all(len(e.link_faces) == 2 for e in bmb.edges)
                depth = max(_depth_into([p for i in sa for p in _face_samples(bma.faces[i])], tb, closed_b),
                            _depth_into([p for i in sb for p in _face_samples(bmb.faces[i])], ta, closed_a))
            # resting rigid bodies overlap by a fraction of a mm (solver margin): size-relative tolerance
            tol = max(0.0005, 0.002 * min((amx - amn).length, (bmx - bmn).length))
            kind = "penetration" if pen and depth > tol else "contact"
            out.append({"a": a.name, "b": b.name, "face_pairs": len(pairs), "penetrating_pairs": pen,
                        "depth_mm": round(depth * 1000, 2), "tolerance_mm": round(tol * 1000, 2),
                        "kind": kind})
    for d in data:
        d[1].free()
    return {"pairs": out, "skipped_large": skipped}


# --------------------------------------------------------------------------- camera
def camera_coverage(cam=None, objs=None, scene=None):
    """Per-object frame status and how much of the frame the subjects fill."""
    from bpy_extras.object_utils import world_to_camera_view
    scene = scene or bpy.context.scene
    cam = cam or scene.camera
    if cam is None:
        return {"error": "no camera"}
    objs = objs or subjects(scene)
    dg = bpy.context.evaluated_depsgraph_get()
    per = []
    ux = [1e9, -1e9, 1e9, -1e9]
    for ob in objs:
        ev = ob.evaluated_get(dg)
        co = [world_to_camera_view(scene, cam, ev.matrix_world @ Vector(c)) for c in ev.bound_box]
        behind = sum(1 for c in co if c.z <= 0)
        xs, ys = [c.x for c in co], [c.y for c in co]
        x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
        if behind == 8 or x1 < 0 or x0 > 1 or y1 < 0 or y0 > 1:
            st = "outside"
        elif behind or x0 < 0 or x1 > 1 or y0 < 0 or y1 > 1:
            st = "cropped"
        else:
            st = "inside"
        per.append({"name": ob.name, "status": st, "bbox_frame": _r([x0, x1, y0, y1], 3)})
        if st != "outside":
            ux = [min(ux[0], x0), max(ux[1], x1), min(ux[2], y0), max(ux[3], y1)]
    fill = 0.0
    if ux[0] < 1e8:
        cx0, cx1, cy0, cy1 = max(0, ux[0]), min(1, ux[1]), max(0, ux[2]), min(1, ux[3])
        fill = max(0, cx1 - cx0) * max(0, cy1 - cy0)
    return {"camera": cam.name, "objects": per, "subject_fill": round(fill, 3),
            "subject_bbox": _r(ux, 3) if ux[0] < 1e8 else None}


def subjects(scene=None):
    """Objects that should be in frame: those tagged obj["bk_subject"]=True, else renderable
    geometry outside collections named Environment/Background/Ground/Sky."""
    scene = scene or bpy.context.scene
    tagged = [o for o in scene.objects if o.get("bk_subject")]
    if tagged:  # include the whole assembly under each tagged object
        out, seen = [], set()
        vis = _render_visible_collections(scene)
        for o in tagged:
            for x in [o] + list(o.children_recursive):
                if x.name not in seen and x.type in GEOMETRY_TYPES and is_render_visible(x, vis):
                    seen.add(x.name)
                    out.append(x)
        return out
    env_words = ("environment", "background", "ground", "sky", "backdrop", "terrain", "set")
    out = []
    for o in renderable(scene):
        names = [c.name.lower() for c in o.users_collection] + [o.name.lower()]
        if any(w in n for n in names for w in env_words):
            continue
        out.append(o)
    return out


# --------------------------------------------------------------------------- images
def sample_object(path, ob, cam=None, radius_px=4, scene=None):
    """Mean display RGB of a rendered image around the projected centre of `ob`.

    Use with a grey card (linear albedo 0.18) to measure exposure objectively:
    AgX/Filmic put a well-exposed 18% card around 0.40-0.55 display value.
    """
    import numpy as np
    from bpy_extras.object_utils import world_to_camera_view
    scene = scene or bpy.context.scene
    cam = cam or scene.camera
    dg = bpy.context.evaluated_depsgraph_get()
    ev = ob.evaluated_get(dg)
    centre = ev.matrix_world @ (sum((Vector(c) for c in ev.bound_box), Vector()) / 8)
    uv = world_to_camera_view(scene, cam, centre)
    img = bpy.data.images.load(path, check_existing=False)
    try:
        w, h = img.size
        px = np.empty(w * h * img.channels, dtype=np.float32)
        img.pixels.foreach_get(px)
        px = px.reshape(h, w, img.channels)
    finally:
        bpy.data.images.remove(img)
    x, y = int(uv.x * w), int(uv.y * h)  # both bottom-up, like Blender's pixel buffer
    if not (0 <= x < w and 0 <= y < h):
        return {"error": "object centre outside frame", "uv": [uv.x, uv.y]}
    patch = px[max(0, y - radius_px):y + radius_px + 1, max(0, x - radius_px):x + radius_px + 1, :3]
    rgb = patch.reshape(-1, 3).mean(axis=0)
    return {"rgb": [round(float(v), 3) for v in rgb], "value": round(float(rgb.mean()), 3),
            "pixel": [x, h - 1 - y]}


def image_stats(path):
    """Exposure analysis of a rendered image (display-referred values)."""
    import numpy as np
    img = bpy.data.images.load(path, check_existing=False)
    try:
        w, h = img.size
        ch = img.channels
        px = np.empty(w * h * ch, dtype=np.float32)
        img.pixels.foreach_get(px)
        px = px.reshape(h, w, ch)
    finally:
        bpy.data.images.remove(img)
    rgb = px[..., :3]
    lum = rgb @ np.array([0.2126, 0.7152, 0.0722], dtype=np.float32)
    alpha_cov = float((px[..., 3] > 0.01).mean()) if ch == 4 else 1.0
    mask = px[..., 3] > 0.01 if ch == 4 and alpha_cov < 0.999 else np.ones_like(lum, dtype=bool)
    L = lum[mask] if mask.any() else lum.ravel()
    mx = rgb.max(axis=-1)[mask] if mask.any() else rgb.max(axis=-1).ravel()
    # fireflies: isolated pixels much brighter than their neighbourhood
    pad = np.pad(lum, 1, mode="edge")
    neigh = np.stack([pad[1 + dy:h + 1 + dy, 1 + dx:w + 1 + dx]
                      for dy in (-1, 0, 1) for dx in (-1, 0, 1) if dy or dx]).mean(axis=0)
    ff = int(((lum > 0.6) & (lum > neigh * 2.5 + 0.1)).sum())
    st = {
        "size": [w, h], "mean": round(float(L.mean()), 3), "median": round(float(np.median(L)), 3),
        "p05": round(float(np.percentile(L, 5)), 3), "p95": round(float(np.percentile(L, 95)), 3),
        "std": round(float(L.std()), 3),
        "clipped_pct": round(float((mx >= 0.995).mean() * 100), 2),
        "crushed_pct": round(float((mx <= 0.005).mean() * 100), 2),
        "fireflies": ff, "alpha_coverage": round(alpha_cov, 3),
        "saturation": round(float((rgb.max(-1) - rgb.min(-1)).mean()), 3),
    }
    v = []
    if st["std"] < 0.02:
        v.append("FLAT: almost uniform image - empty frame, missing lights or camera inside geometry?")
    if st["mean"] < 0.1 and st["p95"] < 0.35:
        v.append("DARK: underexposed - raise light energy/exposure (or confirm low-key intent)")
    if st["mean"] > 0.75 or st["clipped_pct"] > 8:
        v.append("BRIGHT: overexposed / clipping - lower energy or exposure")
    if st["crushed_pct"] > 30:
        v.append("CRUSHED: large pure-black areas - add fill/world light")
    if ff > max(20, w * h * 0.0005):
        v.append("NOISY: fireflies - more samples, clamp indirect, denoise, or soften small bright lights")
    st["verdict"] = v or ["OK"]
    return st
